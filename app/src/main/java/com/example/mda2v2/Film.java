package com.example.mda2v2;

public class Film {
        public String name;
        public String description;
        public int imageId;
        public String genre;
        public String age;



        public Film(String name, String description, int imageId, String genre, String age) {
            this.name = name;
            this.description = description;
            this.imageId = imageId;
            this.genre = genre;
            this.age = age;

        }
    }


